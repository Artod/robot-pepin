"""The head's mouth as one table: config/face.json's parameters, expressions and events.

The mouth on the head's 1.9" screen is procedural: a handful of numbers (width, opening, corner
lift, teeth, a wave along it, ...) draw it, and an expression is nothing but a full set of them.
The firmware tweens every number on its own, so any expression turns smoothly into any other,
and the speech level ('M' frames) opens whatever expression is showing. The face has styles
(``config/face.json`` ``styles``, in the order the 'C' config's byte counts them): the same ids
and names drawn as the cyan line of the pepin style, as line art (rose, manga) or by the
shape-keyframe engine (anime, kawaii, comics: :mod:`pepin.face_shapes`); each expression
carries a look per style, and the head server sends the active style with the 'C' config. A
new style is one entry in that block (a shapes style: ``engine`` shapes and its directory of
drawings, ``like`` an earlier style for the rest). Three readers share the table: the firmware
(``firmware/head_esp32/src/face_table.h``), its desktop simulator
(``firmware/head_esp32/sim/face_table.js``) and the board's head server, which turns names into
the ids the wire carries and robot events into expressions. The two generated files are written
from the JSON by this module, and a unit test refuses a stale copy::

    uv run python -m pepin.face --write     regenerate the files after editing config/face.json
                                            or a keyframe SVG (four files: the parametric
                                            tables and the shape engine's)
    uv run python -m pepin.face --check     exit 1 when a file is stale
    uv run python -m pepin.face             the expressions and events, one per line
    uv run python -m pepin.face --lines     the brain's list of faces (face:NAME, a brief)
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from pepin.overlay import read_json

REPO = Path(__file__).resolve().parents[2]
FIRMWARE = REPO / "firmware" / "head_esp32"
HEADER = FIRMWARE / "src" / "face_table.h"
SCRIPT = FIRMWARE / "sim" / "face_table.js"
FACE_FILE = "face.json"
GENERATED = "Generated by `uv run python -m pepin.face --write` from config/face.json; do not edit."
# The face's elements, each with its own colour per expression (config/face.json `colors` holds
# the defaults; the renderer's slots in this order)
ELEMENTS = ("lip", "cavity", "teeth", "tongue", "cheek", "moustache", "heart", "shade")
# An expression's overlays (the firmware's Effect bits, 1 << index): the heart flies once; the
# sleeper's "z" floats up again and again while a look with it shows (each engine draws its own)
EFFECTS = ("heart", "z")
# The face's styles are config/face.json's `styles` block in its order (the firmware's Style
# enum, the 'C' config's byte); the first is the base look every expression gives in
# `params`/`colors`, the others take their own block (`rose`, `manga`, `anime`, ...). A style's
# `engine` is "params" (the parametric mouth) or "shapes" (the keyframe engine of
# pepin.face_shapes: its mouths are config/<shapes>/*.svg); its `like` names an earlier style
# it starts from (the numbers, the palette, the engine, and its blocks in every expression and
# idle gesture, this style's own over them)
BASE_STYLE = "pepin"
ENGINES = ("params", "shapes")
# The keys a shapes style has beyond the parametric ones (pepin.face_shapes reads them): the
# drawings' directory, the outline's width on the screen, the talk cut's tween, the drool's
# period and the drawings' scale about their common centre
SHAPES_OWN = ("shapes", "line_px", "talk_tween_ms", "drool_s", "scale")
# The geometry numbers a style may set for itself, and the style's own numbers with their
# defaults (the pepin style's: none of the manga rendering)
STYLE_GEOMETRY = ("thick_min_px", "thick_max_px", "tooth_gap_px", "tongue_w_px")
STYLE_OWN = {
    "shade": 0.0,
    "teeth_line_px": 0.0,
    "deco_line_px": 0.0,
    "pucker_line": 0.48,
    "tongue_shine": 0.0,
    "patch_x": 0.0,
    "teeth_span": 1.0,
    "flap_shapes": 0.0,
}
MAX_VARIANTS = 3  # the firmware's kMaxVariants
BRIEF_WORDS = 6  # a brief's most words (the brain's list)
# a later style's block as given: its params, its colours and its effects (None: the
# expression's own), by that style
_Styled = list[tuple[dict[str, Any], dict[str, str], "tuple[str, ...] | None"]]


@dataclass(frozen=True)
class FaceParam:
    """One number of the mouth: its neutral value, its range and what it means."""

    name: str
    default: float
    lo: float
    hi: float
    note: str


@dataclass(frozen=True)
class Look:
    """An expression in one style: its values in the table's parameter order, its elements'
    colours (``#RRGGBB`` in :data:`ELEMENTS` order) and its effects."""

    values: tuple[float, ...]
    colors: tuple[str, ...]
    effects: tuple[str, ...] = ()


@dataclass(frozen=True)
class Expression:
    """A named full set of parameter values per style (the table's ``styles`` order;
    ``values``, ``colors`` and ``effects`` are the first style's), a brief for the brain's
    list, the expressions the firmware may show instead of it at random, and its effects."""

    name: str
    looks: tuple[Look, ...]
    note: str
    brief: str = ""
    variants: tuple[str, ...] = ()
    effects: tuple[str, ...] = ()

    @property
    def values(self) -> tuple[float, ...]:
        """The pepin style's values."""
        return self.looks[0].values

    @property
    def colors(self) -> tuple[str, ...]:
        """The pepin style's colours."""
        return self.looks[0].colors


@dataclass(frozen=True)
class FaceStyle:
    """One way of drawing the face: its elements' colours and the background, its numbers
    (the line's thickness range, the tooth gaps, the shade band, the outlines), its engine
    (``params`` or ``shapes``), for a shapes style its own keys (:data:`SHAPES_OWN`), and the
    earlier style it is ``like`` ('' when none)."""

    name: str
    colors: dict[str, str]
    numbers: dict[str, float]
    engine: str = ENGINES[0]
    own: dict[str, Any] = field(default_factory=dict)
    like: str = ""


@dataclass(frozen=True)
class FaceEvent:
    """What a robot event shows: an expression, how long (None: until replaced or cleared) and
    how strongly (1.0 the expression itself, 0.5 halfway from neutral); ``min_gap_s``: the same
    event from the same source sooner than this after the last is dropped."""

    expression: str
    hold_s: float | None
    intensity: float
    min_gap_s: float = 0.0


@dataclass(frozen=True)
class IdleGesture:
    """One idle gesture: what it adds to the parameters at its peak, for how long, how often
    against the others, whether it may go either way (``mirror``: the sign at random), the
    styles it plays in, and its look in shape space per shapes style (that style's block, or
    the block of the style it is like)."""

    name: str
    weight: float
    duration_s: float
    mirror: bool
    deltas: tuple[float, ...]
    styles: tuple[str, ...] = (BASE_STYLE,)
    shapes: dict[str, dict[str, Any]] = field(default_factory=dict)


@dataclass(frozen=True)
class Idle:
    """The face alive at rest: on which expressions, how often a gesture comes, how long after
    a change or speech none may, how fast one under way fades, and the gestures."""

    enabled: bool
    expressions: tuple[int, ...]
    every_s: tuple[float, float]
    settle_s: float
    fade_s: float
    gestures: tuple[IdleGesture, ...]


@dataclass(frozen=True)
class FaceTable:
    """config/face.json, checked: the parameters, the expressions by id, the events, the
    styles and the one in force."""

    params: tuple[FaceParam, ...]
    expressions: tuple[Expression, ...]
    events: dict[str, FaceEvent]
    geometry: dict[str, float]
    colors: dict[str, str]
    timing: dict[str, float]
    screen: dict[str, int]
    lipsync: dict[str, float]
    idle: Idle
    styles: tuple[FaceStyle, ...] = (FaceStyle(BASE_STYLE, {}, {}),)
    style: str = BASE_STYLE

    @property
    def names(self) -> tuple[str, ...]:
        """The expressions' names, by id."""
        return tuple(e.name for e in self.expressions)

    @property
    def style_names(self) -> tuple[str, ...]:
        """The styles' names in the 'C' config's order (the firmware's Style enum)."""
        return tuple(s.name for s in self.styles)

    @property
    def style_id(self) -> int:
        """The style in force, as the 'C' config carries it (its index in ``styles``)."""
        return self.style_id_of(self.style)

    def style_id_of(self, name: str) -> int:
        """A style's index in ``styles`` (the 'C' config's byte); ``KeyError`` naming the
        known ones otherwise."""
        names = self.style_names
        if name not in names:
            raise KeyError(f"no face style {name!r}; the face has {', '.join(names)}")
        return names.index(name)

    @property
    def shape_styles(self) -> tuple[str, ...]:
        """The names of the styles drawn by the shape engine (none when all are parametric)."""
        return tuple(s.name for s in self.styles if s.engine == "shapes")

    def id_of(self, name: str) -> int:
        """The wire id of an expression; ``KeyError`` naming the known ones otherwise."""
        try:
            return self.names.index(name)
        except ValueError:
            known = ", ".join(self.names)
            raise KeyError(f"no expression {name!r}; the face knows {known}") from None

    def event(self, name: str) -> FaceEvent:
        """What the robot event ``name`` shows; ``KeyError`` naming the known events otherwise."""
        try:
            return self.events[name]
        except KeyError:
            known = ", ".join(self.events)
            raise KeyError(f"no face event {name!r}; the table has {known}") from None


def load_face_table(path: str | Path | None = None) -> FaceTable:
    """config/face.json (or ``path``) checked: every value inside its parameter's range, every
    expression and event naming known things; ``ValueError`` saying what is wrong."""
    if path is None:
        from pepin.deployment import config_file

        path = config_file(FACE_FILE)
    data = read_json(path)
    return parse_face_table(data)


def _color_block(block: dict[str, Any], where: str, allowed: tuple[str, ...]) -> dict[str, str]:
    """``block`` as ``#RRGGBB`` strings over the elements (and what else ``allowed`` names)."""
    own = {str(k): str(v) for k, v in block.items() if k != "note"}
    bad = sorted(set(own) - set(allowed))
    if bad:
        raise ValueError(f"{where}: colors of no element: {', '.join(bad)}")
    for key, color in own.items():
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", color):
            raise ValueError(f"{where}: color {key} #RRGGBB, not {color!r}")
    return own


def parse_face_table(data: dict[str, Any]) -> FaceTable:
    """The table from config/face.json's parsed content (see :func:`load_face_table`)."""
    params = []
    for name, spec in data["params"].items():
        lo, hi = (float(v) for v in spec["range"])
        default = float(spec["default"])
        if not lo <= default <= hi:
            raise ValueError(f"param {name}: default {default} outside {lo}..{hi}")
        params.append(FaceParam(name, default, lo, hi, str(spec.get("note", ""))))
    by_name = {p.name: p for p in params}
    colors = _color_block(data["colors"], "colors", (*ELEMENTS, "background", "text", "accent"))
    missing = [e for e in ELEMENTS if e not in colors]
    if missing:
        raise ValueError(f"colors: no default for {', '.join(missing)}")
    geometry = {k: float(v) for k, v in data["geometry"].items() if k != "note"}
    styles = _styles(data.get("styles", {}), geometry, colors)
    style_names = tuple(s.name for s in styles)
    style = str(data.get("style", BASE_STYLE))
    if style not in style_names:
        raise ValueError(f"style {style!r}: one of {', '.join(style_names)}")
    expressions = []
    # per expression: the params given (its own over its base's), its colours, and the same
    # for each later style's block
    given_of: dict[str, tuple[dict[str, Any], dict[str, str], _Styled, tuple[str, ...]]] = {}
    for entry in data["expressions"]:
        name = str(entry["name"])
        if not re.fullmatch(r"[a-z][a-z_]*", name):
            raise ValueError(f"expression {name!r}: a lower_snake_case name")
        like = entry.get("like")
        if like is not None and str(like) not in given_of:
            raise ValueError(f"expression {name}: like {like!r} is no earlier expression")
        base, base_colors, base_styled, base_effects = (
            given_of[str(like)]
            if like is not None
            else ({}, {}, [({}, {}, None) for _ in styles[1:]], ())
        )
        given = {**base, **dict(entry.get("params", {}))}
        unknown = sorted(set(given) - set(by_name))
        if unknown:
            raise ValueError(f"expression {name}: unknown params {', '.join(unknown)}")
        shade = {
            **base_colors,
            **_color_block(dict(entry.get("colors", {})), f"expression {name}", ELEMENTS),
        }
        styled: _Styled = []
        for i, style_spec in enumerate(styles[1:]):
            style_name = style_spec.name
            block = dict(entry.get(style_name, {}))
            bad = sorted(set(block) - {"params", "colors", "effects", "note"})
            if bad:
                raise ValueError(f"expression {name}: {style_name} has no {', '.join(bad)}")
            own_params = dict(block.get("params", {}))
            unknown = sorted(set(own_params) - set(by_name))
            if unknown:
                raise ValueError(
                    f"expression {name}: {style_name} unknown params {', '.join(unknown)}"
                )
            own_colors = _color_block(
                dict(block.get("colors", {})), f"expression {name}: {style_name}", ELEMENTS
            )
            own_effects = _effects(block.get("effects"), f"expression {name}: {style_name}")
            # the block of the style this one is like, under the base expression's block of
            # this style, under its own
            liked: tuple[dict[str, Any], dict[str, str], tuple[str, ...] | None] = ({}, {}, None)
            if style_spec.like and style_spec.like != BASE_STYLE:
                liked = styled[style_names.index(style_spec.like) - 1]
            effects_i = own_effects if own_effects is not None else base_styled[i][2]
            styled.append(
                (
                    {**liked[0], **base_styled[i][0], **own_params},
                    {**liked[1], **base_styled[i][1], **own_colors},
                    effects_i if effects_i is not None else liked[2],
                )
            )
        effects = _effects(entry.get("effects"), f"expression {name}")
        if effects is None:
            effects = base_effects
        given_of[name] = (given, shade, styled, effects)
        looks = [_look(name, BASE_STYLE, given, {**colors, **shade}, params, effects)]
        for style_spec, (sp, sc, se) in zip(styles[1:], styled, strict=True):
            looks.append(
                _look(
                    name,
                    style_spec.name,
                    {**given, **sp},
                    {**style_spec.colors, **sc},
                    params,
                    se if se is not None else effects,
                )
            )
        brief = str(entry.get("brief", ""))
        if len(brief.split()) > BRIEF_WORDS:
            raise ValueError(f"expression {name}: a brief of at most {BRIEF_WORDS} words")
        expressions.append(
            Expression(
                name,
                tuple(looks),
                str(entry.get("note", "")),
                brief=brief,
                variants=tuple(str(v) for v in entry.get("variants", ())),
                effects=effects,
            )
        )
    names = [e.name for e in expressions]
    if len(set(names)) != len(names):
        raise ValueError("expression names repeat")
    _check_variants(expressions)
    if not names or names[0] != "neutral":
        raise ValueError("expression 0 is neutral: the face the firmware boots into")
    if "sleepy" not in names:
        raise ValueError("the firmware falls asleep into 'sleepy': the table needs it")
    events = {}
    for event, spec in data.get("events", {}).items():
        if event == "note":
            continue
        expression = str(spec["name"])
        if expression not in names:
            raise ValueError(f"event {event}: no expression {expression!r}")
        hold = spec.get("hold_s")
        intensity = float(spec.get("intensity", 1.0))
        if hold is not None and not float(hold) > 0.0:
            raise ValueError(f"event {event}: hold_s is positive or null")
        if not 0.0 <= intensity <= 1.0:
            raise ValueError(f"event {event}: intensity in 0..1")
        gap = float(spec.get("min_gap_s", 0.0))
        if gap < 0.0:
            raise ValueError(f"event {event}: min_gap_s is not negative")
        events[event] = FaceEvent(expression, None if hold is None else float(hold), intensity, gap)
    return FaceTable(
        params=tuple(params),
        expressions=tuple(expressions),
        events=events,
        geometry=geometry,
        colors=colors,
        timing={k: float(v) for k, v in data["timing"].items() if k != "note"},
        screen={k: int(v) for k, v in data["screen"].items() if k != "note"},
        lipsync=_lipsync({k: float(v) for k, v in data["lipsync"].items() if k != "note"}),
        idle=_idle(data.get("idle", {"enabled": False}), names, params, styles),
        styles=styles,
        style=style,
    )


def _effects(given: Any, where: str) -> tuple[str, ...] | None:
    """An effects list checked (known, no repeats); None when none was given."""
    if given is None:
        return None
    effects = tuple(str(e) for e in given)
    for effect in effects:
        if effect not in EFFECTS:
            raise ValueError(f"{where}: effect {effect!r}, one of {', '.join(EFFECTS)}")
    if len(set(effects)) != len(effects):
        raise ValueError(f"{where}: an effect repeats")
    return effects


def _look(
    name: str,
    style: str,
    given: dict[str, Any],
    shade: dict[str, str],
    params: list[FaceParam],
    effects: tuple[str, ...] = (),
) -> Look:
    """An expression's values, colours and effects in one style, each value checked against
    its range."""
    where = f"expression {name}:" + ("" if style == BASE_STYLE else f" {style}")
    values = []
    for param in params:
        value = float(given.get(param.name, param.default))
        if not param.lo <= value <= param.hi:
            raise ValueError(f"{where} {param.name} {value} outside {param.lo}..{param.hi}")
        values.append(value)
    return Look(tuple(values), tuple(shade[e] for e in ELEMENTS), effects)


def _styles(
    block: dict[str, Any], geometry: dict[str, float], colors: dict[str, str]
) -> tuple[FaceStyle, ...]:
    """The styles block, checked, in its order (the 'C' config's byte): the base style first
    (an absent block is the base alone), only known numbers, colours of the elements and the
    background; a style ``like`` an earlier one starts from that one's numbers, colours,
    engine and own keys (never its drawings' directory) and takes its own over them."""
    names = tuple(str(k) for k in block if k != "note") or (BASE_STYLE,)
    if names[0] != BASE_STYLE:
        raise ValueError(f"styles: {BASE_STYLE} first (the base every expression gives)")
    styles: list[FaceStyle] = []
    by_name: dict[str, FaceStyle] = {}
    for name in names:
        if not re.fullmatch(r"[a-z][a-z_]*", name):
            raise ValueError(f"style {name!r}: a lower_snake_case name")
        spec = dict(block.get(name, {}))
        like = str(spec.get("like", ""))
        if like and like not in by_name:
            raise ValueError(f"style {name}: like {like!r} is no earlier style")
        liked = by_name.get(like)
        numbers = (
            dict(liked.numbers)
            if liked
            else {**{k: geometry[k] for k in STYLE_GEOMETRY}, **STYLE_OWN}
        )
        engine = str(spec.get("engine", liked.engine if liked else ENGINES[0]))
        if engine not in ENGINES:
            raise ValueError(f"style {name}: engine {engine!r}, one of {', '.join(ENGINES)}")
        extra = SHAPES_OWN if engine == "shapes" else ()
        bad = sorted(set(spec) - set(numbers) - {"colors", "note", "engine", "like", *extra})
        if bad:
            raise ValueError(f"style {name}: unknown {', '.join(bad)}")
        for key in numbers:
            if key in spec:
                numbers[key] = float(spec[key])
        if not 0.0 <= numbers["shade"] < 1.0:
            raise ValueError(f"style {name}: shade in 0..1")
        own = _color_block(dict(spec.get("colors", {})), f"style {name}", (*ELEMENTS, "background"))
        base = dict(liked.colors) if liked else {k: colors[k] for k in (*ELEMENTS, "background")}
        shapes_own = {k: v for k, v in (liked.own if liked else {}).items() if k != "shapes"}
        shapes_own.update({k: spec[k] for k in extra if k in spec})
        style = FaceStyle(name, {**base, **own}, numbers, engine, shapes_own, like)
        styles.append(style)
        by_name[name] = style
    return tuple(styles)


def _check_variants(expressions: list[Expression]) -> None:
    """Each expression's variants: known, other expressions, without variants of their own (no
    chains), at most :data:`MAX_VARIANTS`."""
    by_name = {e.name: e for e in expressions}
    for e in expressions:
        if len(e.variants) > MAX_VARIANTS:
            raise ValueError(f"expression {e.name}: at most {MAX_VARIANTS} variants")
        if len(set(e.variants)) != len(e.variants):
            raise ValueError(f"expression {e.name}: a variant repeats")
        for v in e.variants:
            if v not in by_name or v == e.name:
                raise ValueError(f"expression {e.name}: variant {v!r} is no other expression")
            if by_name[v].variants:
                raise ValueError(f"expression {e.name}: variant {v} has variants of its own")


def _plays(style: str, listed: tuple[str, ...], likes: dict[str, str]) -> bool:
    """Whether a gesture listing ``listed`` plays in ``style``: listed itself, or like a
    style it plays in."""
    while style:
        if style in listed:
            return True
        style = likes.get(style, "")
    return False


def _idle(
    block: dict[str, Any],
    names: list[str],
    params: list[FaceParam],
    styles: tuple[FaceStyle, ...] = (FaceStyle(BASE_STYLE, {}, {}),),
) -> Idle:
    """The idle block, checked: known expressions and params, a sane span, positive weights and
    durations, at least one gesture when enabled; a gesture plays in the styles it lists (all
    when it lists none) and in those like them, and carries a block per shapes style (its look
    in shape space; a style without one takes the block of the style it is like)."""
    style_names = tuple(s.name for s in styles)
    likes = {s.name: s.like for s in styles}
    shape_names = tuple(s.name for s in styles if s.engine == "shapes")
    enabled = bool(block.get("enabled", True))
    wanted = [str(n) for n in block.get("expressions", [])]
    unknown = [n for n in wanted if n not in names]
    if unknown:
        raise ValueError(f"idle: no expression {', '.join(unknown)}")
    if max((names.index(n) for n in wanted), default=0) >= 32:
        raise ValueError("idle: the firmware's mask holds expressions 0..31")
    lo, hi = (float(v) for v in block.get("every_s", (10.0, 10.0)))
    if not 0.0 < lo <= hi:
        raise ValueError(f"idle: every_s {lo}..{hi}, 0 < min <= max")
    by_name = [p.name for p in params]
    gestures = []
    for spec in block.get("gestures", []):
        name = str(spec["name"])
        given = dict(spec.get("params", {}))
        bad = sorted(set(given) - set(by_name))
        if bad:
            raise ValueError(f"idle gesture {name}: unknown params {', '.join(bad)}")
        weight, duration = float(spec.get("weight", 1.0)), float(spec["duration_s"])
        if not weight > 0.0 or not duration > 0.0:
            raise ValueError(f"idle gesture {name}: weight and duration_s are positive")
        deltas = tuple(float(given.get(p, 0.0)) for p in by_name)
        listed = tuple(str(s) for s in spec.get("styles", style_names))
        bad = sorted(set(listed) - set(style_names))
        if bad or not listed:
            raise ValueError(f"idle gesture {name}: styles are of {', '.join(style_names)}")
        plays = tuple(s for s in style_names if _plays(s, listed, likes))
        shapes: dict[str, dict[str, Any]] = {}
        for s in shape_names:
            shapes[s] = {**shapes.get(likes[s], {}), **dict(spec.get(s, {}))}
        gestures.append(
            IdleGesture(name, weight, duration, bool(spec.get("mirror")), deltas, plays, shapes)
        )
    if enabled and not gestures:
        raise ValueError("idle: enabled with no gesture")
    if not gestures:  # the firmware's arrays need one entry
        gestures.append(IdleGesture("none", 1.0, 1.0, False, (0.0,) * len(params), style_names))
    return Idle(
        enabled=enabled and bool(wanted),
        expressions=tuple(names.index(n) for n in wanted),
        every_s=(lo, hi),
        settle_s=float(block.get("settle_s", 3.0)),
        fade_s=max(1e-3, float(block.get("fade_s", 0.25))),
        gestures=tuple(gestures),
    )


def _lipsync(block: dict[str, float]) -> dict[str, float]:
    """The lip-sync block, checked: a positive window and a floor below full."""
    if not block["window_s"] > 0.0 or not block["floor_db"] < block["full_db"]:
        raise ValueError(f"lipsync {block}: window_s > 0 and floor_db < full_db")
    return block


def mouth_level(rms_dbfs: float, table: FaceTable) -> float:
    """A window's loudness (dBFS) as the mouth's opening, 0..1 (config/face.json lipsync)."""
    lo, hi = table.lipsync["floor_db"], table.lipsync["full_db"]
    return min(max((rms_dbfs - lo) / (hi - lo), 0.0), 1.0)


def rgb565(color: str) -> int:
    """``#RRGGBB`` as the panel's 16-bit RGB565."""
    r, g, b = (int(color[i : i + 2], 16) for i in (1, 3, 5))
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def face_lines(table: FaceTable) -> tuple[str, ...]:
    """The brain's list of faces, one line each: ``face:NAME — brief`` (the mark that shows it);
    the expressions without a brief are left out."""
    return tuple(f"face:{e.name} — {e.brief}" for e in table.expressions if e.brief)


def _camel(name: str) -> str:
    """``max_open_px`` -> ``MaxOpenPx``."""
    return "".join(part.capitalize() for part in name.split("_"))


def _float(value: float) -> str:
    """A C++ float literal."""
    text = repr(float(value))
    return (text if "." in text or "e" in text else text + ".0") + "f"


def render_header(table: FaceTable) -> str:
    """face_table.h: the table as C++ constants for the firmware (and its native tests)."""
    n = len(table.params)
    gestures = table.idle.gestures
    mask = sum(1 << i for i in table.idle.expressions)
    lows = ", ".join(_float(p.lo) for p in table.params)
    highs = ", ".join(_float(p.hi) for p in table.params)
    ids = {e.name: i for i, e in enumerate(table.expressions)}
    style_names = table.style_names

    def variants(e: Expression) -> str:
        found = [ids[v] for v in e.variants] + [-1] * (MAX_VARIANTS - len(e.variants))
        return ", ".join(str(v) for v in found)

    def values_of(style: int) -> list[str]:
        return [
            f"    {{{', '.join(_float(v) for v in e.looks[style].values)}}},  // {i} {e.name}"
            for i, e in enumerate(table.expressions)
        ]

    def colors_of(style: int) -> list[str]:
        return [
            f"    {{{', '.join('0x' + c[1:].upper() + 'u' for c in e.looks[style].colors)}}},"
            f"  // {i} {e.name}"
            for i, e in enumerate(table.expressions)
        ]

    def style_spec(s: FaceStyle) -> str:
        numbers = ", ".join(_float(s.numbers[k]) for k in (*STYLE_GEOMETRY, *STYLE_OWN))
        return f"  {{{numbers}, 0x{rgb565(s.colors['background']):04X}}},  // {s.name}"

    lines = [
        f"// {GENERATED}",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "namespace face {",
        "",
        f"constexpr int kParamCount = {n};",
        "enum Param : uint8_t {",
        *(f"  k{_camel(p.name)} = {i},  // {p.note}" for i, p in enumerate(table.params)),
        "};",
        f"constexpr float kParamMin[kParamCount] = {{{lows}}};",
        f"constexpr float kParamMax[kParamCount] = {{{highs}}};",
        "",
        "// the styles: the same expressions drawn several ways; the host's 'C' config picks one",
        f"constexpr int kStyleCount = {len(style_names)};",
        "enum Style : uint8_t {",
        *(f"  kStyle{_camel(s)} = {i}," for i, s in enumerate(style_names)),
        "};",
        "constexpr const char* kStyleNames[kStyleCount] = {"
        + ", ".join(f'"{s}"' for s in style_names)
        + "};",
        f"constexpr int kStyleDefault = {table.style_id};  // config/face.json `style`",
        "// (a shapes style's entry: flap_shapes and the background; its <style>_table.h has",
        "// the rest)",
        "struct StyleSpec {",
        "  float thick_min_px;   // the line's thickness at thick 0",
        "  float thick_max_px;   // and at thick 1",
        "  float tooth_gap_px;   // the dark gap between two teeth (0: one band)",
        "  float tongue_w_px;    // the tongue's width",
        "  float shade;          // the share of an open mouth's bottom in the shade's colour",
        "  float teeth_line_px;  // a line in the lip's colour under the teeth band (0: none)",
        "  float deco_line_px;   // an outline in the lip's colour round the decorations",
        "  float pucker_line;    // the kiss's stroke, a share of a lobe's radius (0: the line's)",
        "  float tongue_shine;   // the tongue's highlight, a share of its radius (0: a crease)",
        "  float patch_x;        // where the tongue patch's dome peaks along the mouth, -1..1",
        "  float teeth_span;     // the teeth band's reach, a share of the half width",
        "  float flap_shapes;    // the speech level as this many mouth shapes (0: continuous)",
        "  uint16_t background;  // RGB565",
        "};",
        "constexpr StyleSpec kStyles[kStyleCount] = {",
        *(style_spec(s) for s in table.styles),
        "};",
        "",
        f"constexpr int kExpressionCount = {len(table.expressions)};",
        "constexpr const char* kExpressionNames[kExpressionCount] = {",
        *(f'  "{e.name}",' for e in table.expressions),
        "};",
        "// each expression's values, by style",
        "constexpr float kExpressions[kStyleCount][kExpressionCount][kParamCount] = {",
        *(
            line
            for s, name in enumerate(style_names)
            for line in (f"  {{  // {name}", *values_of(s), "  },")
        ),
        "};",
        f"constexpr int kNeutral = {table.id_of('neutral')};",
        f"constexpr int kSleepy = {table.id_of('sleepy')};",
        "",
        "// the face's elements: each expression's colour of each, 0xRRGGBB, by style",
        f"constexpr int kElementCount = {len(ELEMENTS)};",
        "enum Element : uint8_t {",
        *(f"  kEl{_camel(name)} = {i}," for i, name in enumerate(ELEMENTS)),
        "};",
        "constexpr uint32_t kExpressionColors[kStyleCount][kExpressionCount][kElementCount] = {",
        *(
            line
            for s, name in enumerate(style_names)
            for line in (f"  {{  // {name}", *colors_of(s), "  },")
        ),
        "};",
        "",
        "// the expressions shown instead of each at random (-1: none), and each one's effects",
        f"constexpr int kMaxVariants = {MAX_VARIANTS};",
        "constexpr uint8_t kVariantCount[kExpressionCount] = {"
        + ", ".join(str(len(e.variants)) for e in table.expressions)
        + "};",
        "constexpr int8_t kVariants[kExpressionCount][kMaxVariants] = {",
        *(f"  {{{variants(e)}}},  // {i} {e.name}" for i, e in enumerate(table.expressions)),
        "};",
        "enum Effect : uint8_t {",
        *(f"  kEffect{_camel(name)} = {1 << i}," for i, name in enumerate(EFFECTS)),
        "};",
        "// each expression's effects, by style",
        "constexpr uint8_t kExpressionEffects[kStyleCount][kExpressionCount] = {",
        *(
            "  {"
            + ", ".join(
                " | ".join(f"kEffect{_camel(x)}" for x in e.looks[s].effects) or "0"
                for e in table.expressions
            )
            + f"}},  // {name}"
            for s, name in enumerate(style_names)
        ),
        "};",
        "",
        "// screen",
        *(f"constexpr int kScreen{_camel(k)} = {v};" for k, v in table.screen.items()),
        "",
        "// geometry: what each parameter at 1.0 means",
        *(f"constexpr float k{_camel(k)} = {_float(v)};" for k, v in table.geometry.items()),
        "",
        "// timing",
        *(f"constexpr float k{_camel(k)} = {_float(v)};" for k, v in table.timing.items()),
        "",
        "// idle: the face alive at rest",
        f"constexpr bool kIdleOn = {'true' if table.idle.enabled else 'false'};",
        f"constexpr uint32_t kIdleExpressionMask = 0x{mask:08X}u;"
        f"  // {', '.join(table.names[i] for i in table.idle.expressions) or 'none'}",
        f"constexpr float kIdleEveryMinS = {_float(table.idle.every_s[0])};",
        f"constexpr float kIdleEveryMaxS = {_float(table.idle.every_s[1])};",
        f"constexpr float kIdleSettleS = {_float(table.idle.settle_s)};",
        f"constexpr float kIdleFadeS = {_float(table.idle.fade_s)};",
        f"constexpr int kIdleGestureCount = {len(gestures)};",
        "constexpr float kIdleGestureWeight[kIdleGestureCount] = {"
        + ", ".join(_float(g.weight) for g in gestures)
        + "};",
        "constexpr float kIdleGestureDurationS[kIdleGestureCount] = {"
        + ", ".join(_float(g.duration_s) for g in gestures)
        + "};",
        "constexpr bool kIdleGestureMirror[kIdleGestureCount] = {"
        + ", ".join("true" if g.mirror else "false" for g in gestures)
        + "};",
        "constexpr uint8_t kIdleGestureStyles[kIdleGestureCount] = {"
        + ", ".join(f"0x{sum(1 << style_names.index(s) for s in g.styles):02X}" for g in gestures)
        + "};  // a bit per Style",
        "constexpr float kIdleGestures[kIdleGestureCount][kParamCount] = {",
        *(f"  {{{', '.join(_float(v) for v in g.deltas)}}},  // {g.name}" for g in gestures),
        "};",
        "",
        "// colors, RGB565",
        *(
            f"constexpr uint16_t kColor{_camel(k)} = 0x{rgb565(v):04X};  // {v}"
            for k, v in table.colors.items()
        ),
        "",
        "}  // namespace face",
        "",
    ]
    return "\n".join(lines)


def render_script(table: FaceTable) -> str:
    """face_table.js: the same table for the simulator (a plain script: it loads from file://)."""
    payload = {
        "params": [
            {"name": p.name, "default": p.default, "min": p.lo, "max": p.hi, "note": p.note}
            for p in table.params
        ],
        "elements": list(ELEMENTS),
        "styles": [
            {
                "name": s.name,
                "engine": s.engine,
                "colors": s.colors,
                "rgb565": {k: rgb565(v) for k, v in s.colors.items()},
                **{k: s.numbers[k] for k in (*STYLE_GEOMETRY, *STYLE_OWN)},
            }
            for s in table.styles
        ],
        "style": table.style_id,
        "expressions": [
            {
                "name": e.name,
                "looks": [
                    {
                        "values": list(look.values),
                        "colors": [int(c[1:], 16) for c in look.colors],
                        "effects": list(look.effects),
                    }
                    for look in e.looks
                ],
                "variants": [table.id_of(v) for v in e.variants],
                "brief": e.brief,
                "note": e.note,
            }
            for e in table.expressions
        ],
        "events": {
            k: {
                "name": v.expression,
                "hold_s": v.hold_s,
                "intensity": v.intensity,
                "min_gap_s": v.min_gap_s,
            }
            for k, v in table.events.items()
        },
        "idle": {
            "enabled": table.idle.enabled,
            "expressions": list(table.idle.expressions),
            "every_s": list(table.idle.every_s),
            "settle_s": table.idle.settle_s,
            "fade_s": table.idle.fade_s,
            "gestures": [
                {
                    "name": g.name,
                    "weight": g.weight,
                    "duration_s": g.duration_s,
                    "mirror": g.mirror,
                    "deltas": list(g.deltas),
                    "styles": [table.style_id_of(s) for s in g.styles],
                }
                for g in table.idle.gestures
            ],
        },
        "screen": table.screen,
        "geometry": table.geometry,
        "timing": table.timing,
        "lipsync": table.lipsync,
        "colors": table.colors,
        "rgb565": {k: rgb565(v) for k, v in table.colors.items()},
    }
    body = json.dumps(payload, indent=1, ensure_ascii=False)
    return (
        f"// {GENERATED}\n"
        f"const FACE_TABLE = {body};\n"
        'if (typeof module !== "undefined") module.exports = FACE_TABLE;\n'
    )


def generated(table: FaceTable) -> dict[Path, str]:
    """Each generated file and the text it must hold: the parametric tables, and the shape
    engine's when the table has a shapes style (pepin.face_shapes)."""
    from pepin.face_shapes import generated_shapes

    return {HEADER: render_header(table), SCRIPT: render_script(table), **generated_shapes(table)}


def stale(table: FaceTable) -> list[Path]:
    """The generated files whose text differs from what the table renders."""
    return [
        path
        for path, text in generated(table).items()
        if not path.is_file() or path.read_text() != text
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="The head's face table (config/face.json).")
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate the firmware/sim tables")
    mode.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    mode.add_argument("--lines", action="store_true", help="the brain's list of faces")
    args = parser.parse_args(argv)
    # the public file alone: the generated tables are tracked, and a private overlay's faces
    # never enter them (pepin.overlay)
    table = parse_face_table(json.loads((REPO / "config" / FACE_FILE).read_text()))
    if args.write:
        for path, text in generated(table).items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path.relative_to(REPO)}")
        return 0
    if args.lines:
        print("\n".join(face_lines(table)))
        return 0
    if args.check:
        old = stale(table)
        for path in old:
            print(f"stale: {path.relative_to(REPO)} (uv run python -m pepin.face --write)")
        return 1 if old else 0
    print(f"style {table.style} (of {', '.join(table.style_names)})")
    for i, expression in enumerate(table.expressions):
        print(f"{i:2d} {expression.name:<13} {expression.brief}")
    for name, event in table.events.items():
        hold = "held" if event.hold_s is None else f"{event.hold_s:g} s"
        print(f"   {name:<15} -> {event.expression} ({hold}, x{event.intensity:g})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
